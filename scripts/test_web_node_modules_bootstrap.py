#!/usr/bin/env python3
"""クローン直後(apps/web/node_modules が無い状態)から `web` が healthy になることを
宣言レベルで検査する(#1050)。

    python3 -m unittest discover -s scripts -t scripts -p 'test_*.py'

## 背景

`docker-compose.yml` の `web` サービスは `./apps/web:/app` をバインドマウントする。
`apps/web/Dockerfile` の `RUN npm ci --legacy-peer-deps` がイメージ内に作った
`/app/node_modules` は、このバインドマウントに覆い隠される。クローン直後のホストには
`apps/web/node_modules` が存在しないため、`lbs-web` は `sh: next: not found` で
再起動を繰り返す。

## なぜ静的検査なのか

`docker compose up -d` を実際に fresh clone から走らせる検証は
`scripts/verify-web-node-modules-bootstrap.sh`(非破壊、`docker run` 単体で実施)が担う。
ここでは、その場しのぎの手動コマンドではなく**イメージ自身の起動シーケンス**として
解決策が組み込まれていることを検査する。将来 Dockerfile が書き換わって
entrypoint 経由のインストールが失われても、ここが機械的に検出する。
"""

import os
import re
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(HERE, ".."))
DOCKERFILE = os.path.join(REPO_ROOT, "apps/web/Dockerfile")
ENTRYPOINT = os.path.join(REPO_ROOT, "apps/web/docker-entrypoint.sh")
README = os.path.join(REPO_ROOT, "README.md")
SETUP_DOC = os.path.join(REPO_ROOT, "docs/setup.md")


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def exists(path):
    return os.path.isfile(path)


class EntrypointInstallsMissingNodeModules(unittest.TestCase):
    """Dockerfile がホスト側 node_modules 欠落を自前で補うこと。"""

    def test_entrypoint_script_exists(self):
        self.assertTrue(
            exists(ENTRYPOINT),
            "apps/web/docker-entrypoint.sh が無い。node_modules 欠落時に"
            "コンテナ内(node:22-alpineのmusl)で npm ci するエントリポイントが必要(#1050)。",
        )

    def test_dockerfile_uses_the_entrypoint_script(self):
        dockerfile = read(DOCKERFILE)
        self.assertRegex(
            dockerfile,
            r"ENTRYPOINT\s+\[\s*\"[^\"]*docker-entrypoint\.sh\"",
            "apps/web/Dockerfile が docker-entrypoint.sh を ENTRYPOINT に指定していない(#1050)。",
        )

    def test_entrypoint_checks_for_missing_node_modules(self):
        self.assertTrue(exists(ENTRYPOINT), "前提: docker-entrypoint.sh が無い")
        entrypoint = read(ENTRYPOINT)
        self.assertRegex(
            entrypoint,
            r"node_modules",
            "docker-entrypoint.sh が node_modules の有無を見ていない(#1050)。",
        )
        self.assertRegex(
            entrypoint,
            r"npm ci",
            "docker-entrypoint.sh が npm ci を実行していない。ホストの Node と"
            "コンテナの Node(node:22-alpine、musl)が異なりうるため、インストールは"
            "コンテナ内で行う必要がある(#1050)。",
        )

    def test_entrypoint_fixes_ownership_to_the_host_user(self):
        self.assertTrue(exists(ENTRYPOINT), "前提: docker-entrypoint.sh が無い")
        entrypoint = read(ENTRYPOINT)
        self.assertRegex(
            entrypoint,
            r"chown",
            "docker-entrypoint.sh が node_modules の所有者をホストユーザーへ揃えていない。"
            "root 所有のまま残すと #1042 と同種の EACCES を新たに生む(#1050)。",
        )


class DocumentationCoversTheMainDockerFlow(unittest.TestCase):
    """AC4: 手順書の『本線』の Docker 起動手順に、この工程が明記されていること。

    docs/setup.md の「(代替)ホスト上で npm run dev を直接起動する場合」節は
    本線ではないため、そこにしか記載が無い状態は満たさない。
    """

    def test_setup_doc_main_flow_mentions_the_bootstrap(self):
        setup_doc = read(SETUP_DOC)
        section_re = re.search(
            r"^## 5\. Web管理画面.*?(?=^## |\Z)", setup_doc, re.M | re.S
        )
        self.assertIsNotNone(
            section_re, "docs/setup.md に「## 5. Web管理画面」節が見つからない"
        )
        main_section = section_re.group(0)
        alt_start = main_section.find("### (代替)")
        main_only = main_section[: alt_start if alt_start != -1 else len(main_section)]
        self.assertRegex(
            main_only,
            r"node_modules",
            "docs/setup.md の Docker 本線の手順(##5節、代替節より前)に "
            "node_modules 自動インストールの説明が無い(#1050)。",
        )

    def test_readme_startup_section_mentions_first_boot_install(self):
        readme = read(README)
        section_re = re.search(
            r"^## アプリケーションの起動\(Docker\).*?(?=^## |\Z)", readme, re.M | re.S
        )
        self.assertIsNotNone(
            section_re, "README.md に「## アプリケーションの起動(Docker)」節が見つからない"
        )
        self.assertRegex(
            section_re.group(0),
            r"node_modules",
            "README.md の Docker 起動手順に、初回起動時の node_modules 自動インストールに"
            "関する言及が無い(#1050)。",
        )


if __name__ == "__main__":
    unittest.main()
